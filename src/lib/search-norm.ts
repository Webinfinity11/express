// Search normalization: lowercases and transliterates Georgian letters to Latin,
// so "ფრანკო" finds "Franko" (and vice versa).
const MAP: Record<string, string> = {
  ა: "a", ბ: "b", გ: "g", დ: "d", ე: "e", ვ: "v", ზ: "z", თ: "t", ი: "i", კ: "k", ლ: "l", მ: "m",
  ნ: "n", ო: "o", პ: "p", ჟ: "zh", რ: "r", ს: "s", ტ: "t", უ: "u", ფ: "f", ქ: "k", ღ: "gh", ყ: "q",
  შ: "sh", ჩ: "ch", ც: "ts", ძ: "dz", წ: "ts", ჭ: "ch", ხ: "kh", ჯ: "j", ჰ: "h",
};

export function normSearch(text: string): string {
  return text.toLocaleLowerCase().replace(/[ა-ჿ]/g, (c) => MAP[c] ?? c);
}
